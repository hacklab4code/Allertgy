export function getResolvedPhrase(
  template: TravelPhraseTemplate,
  targetLang: string,
  userAllergens: string[]
): string {
  const normLang = (targetLang || 'it').toLowerCase().slice(0, 2);
  const rawTemplate =
    template.templateByLang[normLang] ||
    template.templateByLang['en'] ||
    template.templateByLang['it'] ||
    '';

  let allergenText = '';
  if (userAllergens && userAllergens.length > 0) {
    const names = userAllergens.map((code) => {
      const cleanCode = (code || '').toLowerCase().trim().replace(/[\s-]+/g, '_');
      const dict =
        TRAVEL_ALLERGEN_NAMES[cleanCode] ||
        TRAVEL_ALLERGEN_NAMES[code.toLowerCase().trim()];
      if (dict) {
        return dict[normLang] || dict['en'] || dict['it'] || code;
      }
      return code;
    });
    allergenText = names.join(', ');
  } else {
    allergenText =
      DEFAULT_ALLERGEN_FALLBACK[normLang] ||
      DEFAULT_ALLERGEN_FALLBACK['en'] ||
      'i miei allergeni specificati';
  }

  return rawTemplate.replace(/\{ALLERGENS\}/g, allergenText);
}
